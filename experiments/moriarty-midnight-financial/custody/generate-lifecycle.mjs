function bytesLiteral(hex) {
  if (!/^[0-9a-f]{64}$/.test(hex)) throw new Error(`expected 32-byte hex, got ${hex}`);
  const nums = [];
  for (let i = 0; i < 64; i += 2) nums.push(String(parseInt(hex.slice(i, i + 2), 16)));
  return `Bytes[${nums.join(', ')}]`;
}

function timeCircuits() {
  return `
circuit capabilityHash(domain: Bytes<32>, network: Bytes<32>, program: Bytes<32>, secret: Bytes<32>): Bytes<32> {
  return persistentHash<Vector<4, Bytes<32>>>([domain, network, program, secret]);
}

circuit constrainNow(now: Uint<64>): Uint<128> {
  const publicNow: Uint<64> = disclose(now);
  const maxNow: Uint<64> = 18446744073709551315;
  assert(publicNow <= maxNow, "UINT64_WINDOW_OVERFLOW");
  const windowEnd: Uint<64> = ((publicNow as Uint<128>) + 300) as Uint<64>;
  assert(blockTimeGte(publicNow), "BLOCK_TIME_TOO_EARLY");
  assert(blockTimeLt(windowEnd), "BLOCK_TIME_TOO_LATE");
  assert(publicNow < 2000000000, "HORIZON_EXPIRED");
  return publicNow as Uint<128>;
}
`;
}

/** Additive, uncompiled authority/fee disbursement wrapper. The legacy kernels
 * and wrapper receipts remain unchanged. Full lifecycle correspondence is open. */
export function generateLifecycleWrapper({source}) {
  const binding=lowerLifecycleSourceBinding(source);
  const wrapper=`pragma language_version >= 0.23 && <= 0.23;
import CompactStandardLibrary;
// Generated by custody/generate-lifecycle.mjs. UNCOMPILED: task 5.2a owns compilation.
// Scope: authority/fee disbursement. Full lifecycle transitions remain open.
// sourceHash=${binding.sourceDigest}
// coreHash=${binding.coreDigest}
// sourceProfile=${binding.sourceProfile}
// coreContract=${binding.coreContract}
export ledger programDigest: Bytes<32>;
export ledger sourceDigest: Bytes<32>;
export ledger coreDigest: Bytes<32>;
export ledger networkTag: Bytes<32>;
export ledger borrowerCapability: Bytes<32>;
export ledger lenderCapability: Bytes<32>;
export ledger borrowerAddress: UserAddress;
export ledger lenderAddress: UserAddress;
export ledger cashColor: Bytes<32>;
export ledger revision: Uint<128>;
export ledger originated: Boolean;
// These are transaction intent caps, NOT the unresolved lifecycle allowance state.
export ledger borrowerGrossCap: Uint<128>;
export ledger lenderGrossCap: Uint<128>;
export ledger borrowerHasNetGoal: Boolean;
export ledger lenderHasNetGoal: Boolean;
export ledger borrowerMinimumNetCredit: Uint<128>;
export ledger lenderMinimumNetCredit: Uint<128>;
${timeCircuits()}
pure circuit checkedAdd(a: Uint<128>, b: Uint<128>): Uint<128> {
  const sum = a + b;
  assert(sum <= 340282366920938463463374607431768211455, "INTENT_ARITHMETIC_OVERFLOW");
  return sum as Uint<128>;
}
constructor(borrowerSecret: Bytes<32>, lenderSecret: Bytes<32>, borrowerPayout: UserAddress, lenderPayout: UserAddress, expectedProgram: Bytes<32>, expectedNetwork: Bytes<32>, settlementColor: Bytes<32>, debtorCap: Uint<128>, creditorCap: Uint<128>, debtorHasGoal: Boolean, creditorHasGoal: Boolean, debtorMinimum: Uint<128>, creditorMinimum: Uint<128>) {
  const pinnedProgram: Bytes<32> = ${bytesLiteral(binding.programDigest)};
  assert(expectedProgram == pinnedProgram, "PROGRAM_MISMATCH");
  programDigest = pinnedProgram;
  sourceDigest = ${bytesLiteral(binding.sourceDigest)};
  coreDigest = ${bytesLiteral(binding.coreDigest)};
  networkTag = disclose(expectedNetwork);
  borrowerCapability = disclose(capabilityHash(pad(32, "moriarty:sp05:loan:borrower"), expectedNetwork, pinnedProgram, borrowerSecret));
  lenderCapability = disclose(capabilityHash(pad(32, "moriarty:sp05:loan:lender"), expectedNetwork, pinnedProgram, lenderSecret));
  borrowerAddress = disclose(borrowerPayout);
  lenderAddress = disclose(lenderPayout);
  cashColor = disclose(settlementColor);
  borrowerGrossCap = disclose(debtorCap);
  lenderGrossCap = disclose(creditorCap);
  borrowerHasNetGoal = disclose(debtorHasGoal);
  lenderHasNetGoal = disclose(creditorHasGoal);
  borrowerMinimumNetCredit = disclose(debtorMinimum);
  lenderMinimumNetCredit = disclose(creditorMinimum);
  revision = 0;
  originated = false;
}
export circuit originate(borrowerSecret: Bytes<32>, lenderSecret: Bytes<32>, expectedProgram: Bytes<32>, expectedNetwork: Bytes<32>, expectedRevision: Uint<128>, expectedActor: Uint<32>, expectedDebtor: Uint<32>, privateFeeAmount: Uint<128>, now: Uint<64>): [] {
  assert(expectedProgram == programDigest, "PROGRAM_MISMATCH");
  assert(expectedNetwork == networkTag, "NETWORK_MISMATCH");
  assert(expectedRevision == revision, "REVISION_MISMATCH");
  assert(!originated, "ALREADY_ORIGINATED");
  assert(capabilityHash(pad(32, "moriarty:sp05:loan:lender"), networkTag, programDigest, lenderSecret) == lenderCapability, "LENDER_CAPABILITY");
  assert(capabilityHash(pad(32, "moriarty:sp05:loan:borrower"), networkTag, programDigest, borrowerSecret) == borrowerCapability, "BORROWER_CAPABILITY");
  assert(expectedActor == 5, "ACTOR_MAPPING");
  assert(expectedDebtor == 2, "ACTOR_MAPPING");
  constrainNow(now);
  const feeAmount: Uint<128> = disclose(privateFeeAmount);
  const disbursement: Uint<128> = ${binding.disbursementAmount};
  assert(disbursement <= lenderGrossCap, "INTENT_DEBIT_CAP");
  assert(feeAmount <= borrowerGrossCap, "INTENT_DEBIT_CAP");
  if (borrowerHasNetGoal) {
    assert(disbursement >= checkedAdd(feeAmount, borrowerMinimumNetCredit), "INTENT_NET_GOAL");
  }
  if (lenderHasNetGoal) {
    assert(feeAmount >= checkedAdd(disbursement, lenderMinimumNetCredit), "INTENT_NET_GOAL");
  }
  // Separate economic Fee and disbursement legs. No DUST conversion is implied.
  receiveUnshielded(cashColor, disbursement);
  sendUnshielded(cashColor, disbursement, right<ContractAddress, UserAddress>(borrowerAddress));
  receiveUnshielded(cashColor, feeAmount);
  sendUnshielded(cashColor, feeAmount, right<ContractAddress, UserAddress>(lenderAddress));
  revision = checkedAdd(revision, 1);
  originated = true;
}
`;
  return {source:wrapper,binding};
}


export function runLifecycleGenerateCli(argv=process.argv) {
  const i=argv.indexOf('--output-dir');
  if(i<0||!argv[i+1])throw Error('missing --output-dir');
  const here=dirname(fileURLToPath(import.meta.url));
  const source=readFileSync(join(here,'../../moriarty-language/spec/successor/examples/loan-lifecycle-fee.mori'),'utf8');
  const generated=generateLifecycleWrapper({source}),outputDir=resolve(argv[i+1]);
  mkdirSync(outputDir,{recursive:true});
  writeFileSync(join(outputDir,'loan-lifecycle.compact'),generated.source);
  return {outputDir,binding:generated.binding};
}
if(isDirectRun(import.meta.url))runLifecycleGenerateCli();
