"""Generate semantics/zkir-constants.k from midnight-circuits 7.2.4 sources.

Reads the Poseidon round constants and MDS matrix for the BLS12-381 scalar
field (hash/poseidon/constants/blstrs.rs, produced by the pasta-hadeshash grain
script for t=3, R_F=8, R_P=60) and the Jubjub map-to-curve parameters
(ecc/hash_to_curve/mtc_params.rs). `Fq::from_raw([a, b, c, d])` are the four
little-endian 64-bit limbs of the canonical integer.

Usage: python gen_constants.py <midnight-circuits-src-dir> > ../semantics/zkir-constants.k
"""
import re
import sys
from pathlib import Path

src = Path(sys.argv[1])
FROM_RAW = re.compile(r'from_raw\(\s*\[([^\]]*)\]\s*\)', re.S)


def limbs_to_int(text: str) -> int:
    limbs = [int(x.replace('_', ''), 16) for x in re.findall(r'0x[0-9a-fA-F_]+', text)]
    assert len(limbs) == 4, limbs
    return sum(l << (64 * i) for i, l in enumerate(limbs))


blstrs = (src / 'hash/poseidon/constants/blstrs.rs').read_text()
rc_start = blstrs.index('const ROUND_CONSTANTS')
mds_start = blstrs.index('const MDS')
rc_text, mds_text = (blstrs[rc_start:mds_start], blstrs[mds_start:]) if rc_start < mds_start else (blstrs[rc_start:], blstrs[mds_start:rc_start])
rcs = [limbs_to_int(m) for m in FROM_RAW.findall(rc_text)]
mds = [limbs_to_int(m) for m in FROM_RAW.findall(mds_text)]
assert len(rcs) == 68 * 3, len(rcs)
assert len(mds) == 9, len(mds)

mtc = (src / 'ecc/hash_to_curve/mtc_params.rs').read_text()
consts = {}
for name in ['SVDW_Z', 'A', 'B', 'MONT_J', 'MONT_K']:
    m = re.search(r'const %s: JubjubBase = JubjubBase::from_raw\(\s*\[([^\]]*)\]' % name, mtc, re.S)
    consts[name] = limbs_to_int(m.group(1))

out = []
out.append('// GENERATED by tools/gen_constants.py from midnight-circuits 7.2.4; do not edit.')
out.append('// Poseidon (BLS12-381 scalar field, t=3, R_F=8, R_P=60) round constants and MDS,')
out.append('// and the Jubjub Shallue-van de Woestijne map-to-curve parameters.')
out.append('module ZKIR-CONSTANTS')
out.append('  imports INT')
out.append('  syntax Int ::= poseidonRC(Int, Int) [function, total]   // round 0..67, position 0..2')
for r in range(68):
    for j in range(3):
        out.append(f'  rule poseidonRC({r}, {j}) => {rcs[r * 3 + j]}')
out.append('  rule poseidonRC(_, _) => 0 [owise]')
out.append('  syntax Int ::= poseidonMDS(Int, Int) [function, total]')
for i in range(3):
    for j in range(3):
        out.append(f'  rule poseidonMDS({i}, {j}) => {mds[i * 3 + j]}')
out.append('  rule poseidonMDS(_, _) => 0 [owise]')
for name, k in [('SVDW_Z', 'svdwZ'), ('A', 'svdwA'), ('B', 'svdwB'), ('MONT_J', 'montJ'), ('MONT_K', 'montK')]:
    out.append(f'  syntax Int ::= "#{k}" [function, total]')
    out.append(f'  rule #{k} => {consts[name]}')
out.append('endmodule')
print('\n'.join(out))
