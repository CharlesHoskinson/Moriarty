"""Real transaction contexts for the seven Moriarty artifacts (plan-iter3 M4).

Runs every preimage under corpus/moriarty-contexts/ (produced from the compiled
contracts by tools/moriarty_preimages.mjs; see manifest.json) through the K
semantics (checkedJob: static check then the witness run), the crate's
`preprocess` (zkir-oracle) and the halo2 MockProver (zkir-circuit-oracle), and
prints one table row per artifact: status on each side, agreement (the
diff_test comparison: status, error class, registers, public inputs, skips),
and the circuit outcome with k and time. The negative controls per artifact,
which every side must reject: `wrong-phase` (the first ledger read, the phase
cell, + 1, with the program-verified public transcript inputs regenerated by
the K generation mode so that only the ledger value is wrong) and, where the
circuit calls a witness, `wrong-witness` (last private transcript element + 1,
so the authority hash no longer matches the ledger). Both must fail the
contract's own assertion, not a transcript-format check.

Base surface (ZKIR definition, ledger-92e8bdd3 binaries) by default; --ext adds
the same runs on the ZKIR-EXT definition and the midnight-zkir-2ffe2d1 binaries.

Usage: uv run --group zkir-k python experiments/zkir-k/tools/moriarty_contexts.py [--ext] [--no-negative] [--only NAME]
Exit status 0 iff every honest row is ok/ok/agree/accepted and every negative row is rejected on all three sides.
"""
from __future__ import annotations

import argparse
import json
import subprocess
import sys
import tempfile
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import diff_test  # noqa: E402
import zkir_kast  # noqa: E402
from zkir_run import R, Runner  # noqa: E402

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
REPO = ROOT.parent.parent
CONTEXTS = ROOT / 'corpus' / 'moriarty-contexts'
BUILD = Path.home() / 'Moriarty/repos/_build'
SURFACES = {
    'base': {'ws': BUILD / 'ledger-92e8bdd3', 'ext': False, 'label': 'ZKIR / ledger-92e8bdd3'},
    'ext': {'ws': BUILD / 'midnight-zkir-2ffe2d1', 'ext': True, 'label': 'ZKIR-EXT / midnight-zkir-2ffe2d1'},
}
PROGRAMS = {
    'swap': REPO / 'experiments' / 'moriarty-core-swap' / 'output' / 'zkir',
    'escrow': REPO / 'experiments' / 'moriarty-compact-escrow' / 'output' / 'zkir',
}


def program_path(name: str) -> Path:
    contract, circuit = name.split('-', 1)
    return PROGRAMS[contract] / f'{circuit}.zkir'


def circuit_oracle(binary: Path, program: Path, pre: dict) -> dict:
    with tempfile.NamedTemporaryFile('w', suffix='.json') as f:
        json.dump(pre, f)
        f.flush()
        res = subprocess.run([str(binary), str(program), f.name], capture_output=True, text=True)
    if res.returncode != 0:
        return {'outcome': 'load-error', 'message': res.stderr.strip()[-300:]}
    return json.loads(res.stdout.splitlines()[-1])


def short(msg: str, n: int = 44) -> str:
    return (msg or '').replace('\n', ' ')[:n]


def run_surface(surface: str, names: list[str], negative: bool) -> tuple[list[str], int]:
    cfg = SURFACES[surface]
    runner = Runner(ext=cfg['ext'])
    zkir_oracle = cfg['ws'] / 'target/release/zkir-oracle'
    circ = cfg['ws'] / 'target/release/zkir-circuit-oracle'
    diff_test.ORACLE_BIN = zkir_oracle
    lines = [f"Surface {cfg['label']}: K definition {runner.krun.definition_dir}", f'  preprocess oracle {zkir_oracle}', f'  circuit oracle    {circ}', '']
    header = f"{'artifact':<27}{'case':<15}{'K':<10}{'preprocess':<12}{'agreement':<10}{'circuit':<28}{'k':>3}{'ms':>7}  notes"
    lines += [header, '-' * len(header)]
    failures = 0
    for name in names:
        program = program_path(name)
        honest = json.loads((CONTEXTS / f'{name}.pre.json').read_text())
        cases = [('honest', honest)]
        kprog = zkir_kast.load_program(program, ext=cfg['ext'])
        if negative:
            bad = json.loads(json.dumps(honest))
            bad['public_transcript_outputs'][0] = str((int(bad['public_transcript_outputs'][0]) + 1) % R)
            gen = runner.run(kprog, bad, gen=True)
            bad['public_transcript_inputs'] = [str(x) for kind, x in gen['needs'] if kind == 'pubIn']
            cases.append(('wrong-phase', bad))
            if honest['private_transcript']:
                bad = json.loads(json.dumps(honest))
                bad['private_transcript'][-1] = str((int(bad['private_transcript'][-1]) + 1) % R)
                cases.append(('wrong-witness', bad))
        for case, pre in cases:
            t0 = time.time()
            k = runner.run(kprog, pre, checked=True)
            k_ms = int((time.time() - t0) * 1000)
            r = diff_test.oracle(program, pre)
            diffs = diff_test.compare(k, r)
            c = circuit_oracle(circ, program, pre)
            outcome = c.get('outcome', '?')
            notes = []
            if k['status'] == 'ok':
                notes.append(f"regs={len(k['memory'])} pis={len(k['pis'])} verdicts={k['verdicts']} non-holding={len(k['violations'])} K {k_ms}ms")
            else:
                notes.append(f"K '{short(k.get('error', ''))}'")
            if r['status'] != 'ok':
                notes.append(f"Rust '{short(r.get('error', ''))}'")
            if outcome not in ('accepted',):
                notes.append(f"circuit '{short(c.get('message', ''), 60)}'")
            if diffs:
                notes.append('DIFF ' + '; '.join(d[:80] for d in diffs[:2]))
            agree = 'agree' if not diffs else 'DIFFER'
            if case == 'honest':
                ok = k['status'] == 'ok' and r['status'] == 'ok' and not diffs and outcome == 'accepted' and not k['violations']
            else:
                ok = (k['status'] == 'error' and r['status'] == 'error' and not diffs and outcome != 'accepted'
                      and diff_test.err_class(k.get('error', '')) == 'assertion')
            failures += not ok
            mark = '' if ok else '  <-- FAIL'
            lines.append(f"{name:<27}{case:<15}{k['status']:<10}{r['status']:<12}{agree:<10}{outcome:<28}{str(c.get('k', '')):>3}{str(c.get('elapsed_ms', '')):>7}  {' | '.join(notes)}{mark}")
    lines.append('')
    return lines, failures


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument('--ext', action='store_true', help='also run the ZKIR-EXT definition and the midnight-zkir-2ffe2d1 binaries')
    ap.add_argument('--no-negative', action='store_true')
    ap.add_argument('--only', default='')
    args = ap.parse_args()
    manifest = json.loads((CONTEXTS / 'manifest.json').read_text())
    names = [n for n in manifest['artifacts'] if args.only in n]
    print(f"Moriarty transaction contexts (plan-iter3 M4): {len(names)} preimages under {CONTEXTS.relative_to(REPO)}")
    print(f"  produced {manifest['produced']} by {manifest['method']}: {manifest['how']}")
    print(f"  {manifest['fixed_fields']}")
    print()
    for n in names:
        a = manifest['artifacts'][n]
        print(f"  {n:<27} {a['circuit']:<20} time={a['time']} inputs={a['inputs']} sizes={a['sizes']}")
        print(f"  {'':<27} {a['scenario']}")
    print()
    failures = 0
    for surface in (['base', 'ext'] if args.ext else ['base']):
        lines, f = run_surface(surface, names, not args.no_negative)
        print('\n'.join(lines))
        failures += f
    print(f"{failures} failing rows" if failures else 'all rows as expected')
    return 1 if failures else 0


if __name__ == '__main__':
    sys.exit(main())
