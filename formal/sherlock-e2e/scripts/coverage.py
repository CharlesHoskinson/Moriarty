#!/usr/bin/env python3
"""Merge the per-context coverage.tsv files into COVERAGE-FORMAL-B.md and write the
requirement table of each context's lean/README.md. Checks:
  * every in-scope ID (reqs.json) has exactly one row; no unknown ID; no blank verdict;
  * the verdict is one of MODELED, CONSTANT-CHECKED, SPEC-CHECKED, FINDING;
  * every Lean name in a row is a theorem or def of that context, and every theorem is
    pinned in its Audit.lean;
  * no `sorry` in any Lean module.
Usage: coverage.py <reqs.json>   (exit 1 on any defect)"""
import json, pathlib, re, sys

here = pathlib.Path(__file__).resolve().parent.parent
reqs = json.load(open(sys.argv[1]))
CTX = {"leaf-proving": "LeafProving", "aggregation": "Aggregation", "bridge": "Bridge",
       "key-management": "KeyManagement", "scheduling": "Scheduling",
       "box-fleet": "BoxFleet", "assurance": "Assurance"}
VERDICTS = {"MODELED", "CONSTANT-CHECKED", "SPEC-CHECKED", "FINDING"}
SHARED_C = set()
for fam, lo, hi in [("DG", 1, 3), ("DG", 10, 10), ("LW", 1, 22), ("ANC", 12, 16), ("ZK", 1, 1),
                    ("ZK", 9, 9), ("ZK", 12, 12), ("ZK", 18, 18), ("PRD", 2, 3), ("GPW", 7, 7),
                    ("RSL", 1, 8), ("LPC", 5, 5), ("LPC", 16, 16), ("LPC", 18, 18)]:
    for n in range(lo, hi + 1):
        SHARED_C.add(f"{fam}-{n:03d}")
defects, rows = [], {}
for ctx, ns in CTX.items():
    tsv = here / ctx / "coverage.tsv"
    if not tsv.exists():
        defects.append(f"{ctx}: no coverage.tsv"); continue
    lean = here / ctx / "lean"
    src = "\n".join(p.read_text() for p in (lean / ns).glob("*.lean")) if (lean / ns).exists() else ""
    names = set(re.findall(r"^(?:theorem|def|abbrev)\s+([A-Za-z0-9_'.]+)", src, re.M))
    audit = (lean / ns / "Audit.lean").read_text() if (lean / ns / "Audit.lean").exists() else ""
    for p in list((lean / ns).glob("*.lean")) + [lean / "Main.lean"]:
        if p.exists() and re.search(r"\bsorry\b", re.sub(r"--.*|/-.*?-/", "", p.read_text(), flags=re.S)):
            defects.append(f"{p}: sorry")
    for line in tsv.read_text().splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        f = line.split("\t")
        if len(f) != 4:
            defects.append(f"{ctx}: bad row {line!r}"); continue
        i, verdict, leanNames, note = f
        if i in rows:
            defects.append(f"{i}: duplicate row ({rows[i]['ctx']}, {ctx})")
        if verdict not in VERDICTS:
            defects.append(f"{i}: verdict {verdict!r}")
        if not note.strip():
            defects.append(f"{i}: blank note")
        for n in [x.strip() for x in leanNames.split(",") if x.strip()]:
            if n not in names:
                defects.append(f"{i}: Lean name {n} not in {ns}")
            elif re.search(rf"^theorem\s+{re.escape(n)}\b", src, re.M) and f"#print axioms {ns}.{n}\n" not in audit:
                defects.append(f"{i}: theorem {n} not pinned in Audit.lean")
        if verdict in ("MODELED", "CONSTANT-CHECKED") and not leanNames.strip():
            defects.append(f"{i}: {verdict} without a Lean name")
        rows[i] = dict(ctx=ctx, verdict=verdict, lean=leanNames, note=note)
for i in reqs:
    if i not in rows:
        defects.append(f"{i}: no row")
for i in rows:
    if i not in reqs:
        defects.append(f"{i}: not an in-scope ID")

def key(i):
    fam, n = i.rsplit("-", 1)
    return (fam, int(n))

counts = {}
for r in rows.values():
    counts[r["verdict"]] = counts.get(r["verdict"], 0) + 1
out = ["# COVERAGE-FORMAL, slice B part (Formal-Lean-B)", "",
       "Generated by `formal/sherlock-e2e/scripts/coverage.py` from `formal/sherlock-e2e/<context>/coverage.tsv`. "
       "One row per EARS ID of slice B: the 127 IDs of the 13 slice B specs and the reused IDs that "
       "`bus/ddd-B.md` and the slice B DONE line adopt. Verdicts follow `research/sherlock-e2e-spec-20261115/FORMAL-BRIEF.md`.", "",
       "MODELED rows: the Lean theorem exists and builds with 0 `sorry`; the Quint invariant and the replay "
       "are the Formal-Quint lane's (column Replay). A MODELED row counts as final only when Replay reads `agrees`. "
       "Shared = the ID is also adopted by slice C (`bus/adopted-C.md`); the merge keeps this one row.", "",
       "Counts: " + ", ".join(f"{k} {v}" for k, v in sorted(counts.items())) + f"; total {len(rows)} "
       f"({sum(1 for r in reqs.values() if r['kind']=='own')} own, {sum(1 for r in reqs.values() if r['kind']=='reused')} reused).", ""]
for ctx, ns in CTX.items():
    ids = sorted([i for i, r in rows.items() if r["ctx"] == ctx], key=lambda i: (reqs.get(i, {}).get("kind") != "own", key(i)))
    out += [f"## {ctx} (`{ctx}/lean`, namespace `{ns}`)", "",
            "| ID | Source | Verdict | Lean | Replay | Note |", "|---|---|---|---|---|---|"]
    for i in ids:
        r = rows[i]; q = reqs.get(i, {})
        src = q.get("src", "?").replace("sherlock-", "").replace("-2026111", "-2026111")
        shared = " (shared with C)" if i in SHARED_C else ""
        replay = "pending (Formal-Quint)" if r["verdict"] == "MODELED" else "n/a"
        lean = ", ".join(f"`{n.strip()}`" for n in r["lean"].split(",") if n.strip())
        out.append(f"| {i} | {src}{shared} | {r['verdict']} | {lean} | {replay} | {r['note']} |")
    out.append("")
    # README requirement table
    readme = here / ctx / "lean" / "README.md"
    if (here / ctx / "lean").exists():
        t = [f"# {ns} oracle", "", f"Lean oracle of the {ctx} context (slice B). Interface: `../ORACLE.md`. "
             "Build: `formal/sherlock-e2e/scripts/odin-build.sh " + ctx + "`. Audit: `" + ns + "/Audit.lean` (generated by `scripts/gen-audit.py`).", "",
             "## Requirement table", "", "| ID | Sentence (spec text) | Lean | Verdict |", "|---|---|---|---|"]
        for i in ids:
            s = reqs.get(i, {}).get("sentence", "").replace("|", "\\|").replace("\n", " ")
            t.append(f"| {i} | {s} | {', '.join('`'+n.strip()+'`' for n in rows[i]['lean'].split(',') if n.strip())} | {rows[i]['verdict']} |")
        readme.write_text("\n".join(t) + "\n")
(here / "COVERAGE-FORMAL-B.md").write_text("\n".join(out) + "\n")
print("rows", len(rows), "of", len(reqs), counts)
if defects:
    print("DEFECTS:", *defects[:80], sep="\n  ")
    print(f"{len(defects)} defects")
    sys.exit(1)
print("coverage: OK")
