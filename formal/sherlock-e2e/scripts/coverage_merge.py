#!/usr/bin/env python3
"""Merge COVERAGE-FORMAL-B.md and COVERAGE-FORMAL-AC.md into COVERAGE-FORMAL.md, one row per EARS ID.

usage: coverage_merge.py   (reads and writes files next to this folder)
A row that both parts hold keeps the stronger verdict (FINDING, then MODELED, CONSTANT-CHECKED,
SPEC-CHECKED); the Lean, replay and note cells of both parts are kept, B first.
AC pointer rows ("see COVERAGE-FORMAL-B.md") must have a B row. exit 1 on a missing or bad row.
"""
import collections, pathlib, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
RANK = {"FINDING": 4, "MODELED": 3, "CONSTANT-CHECKED": 2, "SPEC-CHECKED": 1}
errors = []


def cells(line):
    return [x.strip() for x in line.strip().strip("|").split("|")]


b, ctx = {}, None
for line in (ROOT / "COVERAGE-FORMAL-B.md").read_text().splitlines():
    if line.startswith("## ") and "(`" in line:
        ctx = line[3:].split(" ")[0]
    elif line.startswith("## "):
        ctx = None
    if ctx is None or not line.startswith("| ") or line.startswith("| ID") or line.startswith("|---"):
        continue
    c = cells(line)
    # ID | Source | Verdict | Lean | Replay | Note
    if c[0] in b:
        errors.append(f"B duplicate {c[0]}")
    b[c[0]] = {"slice": "B", "ctx": ctx, "verdict": c[2], "source": c[1], "lean": c[3], "replay": c[4], "note": c[5]}

ac, pointers = {}, set()
for line in (ROOT / "COVERAGE-FORMAL-AC.md").read_text().splitlines():
    if not line.startswith("| ") or line.startswith("| ID") or line.startswith("|---") or line.startswith("| verdict"):
        continue
    c = cells(line)
    if len(c) == 5 and c[3] == "see COVERAGE-FORMAL-B.md":
        pointers.add(c[0])
        continue
    if len(c) < 7 or c[3] not in RANK:
        continue
    # ID | group | context | verdict | Lean | Quint/replay | source / reason
    if c[0] in ac:
        errors.append(f"AC duplicate {c[0]}")
    ac[c[0]] = {"slice": "A" if c[1] == "A" else ("C" if c[1] == "C" else c[1]), "ctx": c[2], "verdict": c[3],
                "source": "", "lean": c[4], "replay": c[5], "note": c[6]}

for p in sorted(pointers):
    if p not in b:
        errors.append(f"pointer row {p} has no B row")

rows, shared = {}, []
for rid in sorted(set(b) | set(ac)):
    if rid in b and rid in ac:
        x, y = b[rid], ac[rid]
        shared.append(rid)
        best = x if RANK[x["verdict"]] >= RANK[y["verdict"]] else y
        rows[rid] = {"slice": f"B+{y['slice']}", "ctx": f"{x['ctx']} / {y['ctx']}", "verdict": best["verdict"],
                     "lean": f"B: {x['lean'] or '-'}; AC: {y['lean'] or '-'}",
                     "replay": f"B: {x['replay']}; AC: {y['replay']}",
                     "note": f"B: {x['note']} AC: {y['note']}"}
    else:
        r = b.get(rid) or ac[rid]
        rows[rid] = dict(r)
        if r is b.get(rid):
            rows[rid]["note"] = (f"{r['source']}: " if r["source"] else "") + r["note"]
for k, r in rows.items():
    if not all([r["verdict"], r["note"]]):
        errors.append(f"{k}: blank cell")
if errors:
    print("\n".join(errors), file=sys.stderr)
    sys.exit(1)

counts = collections.Counter(r["verdict"] for r in rows.values())
by_slice = collections.Counter(r["slice"].split("+")[0] if "+" not in r["slice"] else "shared" for r in rows.values())
out = ["# COVERAGE-FORMAL: formal coverage of the Sherlock end-to-end prototype spec", "",
       "Generated by `formal/sherlock-e2e/scripts/coverage_merge.py` from COVERAGE-FORMAL-B.md (slice B,",
       "Formal-Lean-B) and COVERAGE-FORMAL-AC.md (slices A and C and change sherlock-completion-20261115,",
       "Formal-Lean-AC). One row per EARS ID. An ID that both parts hold (the DG, LW, ANC, ZK, PRD and other",
       "adopted rows) keeps the stronger verdict in the order FINDING, MODELED, CONSTANT-CHECKED,",
       "SPEC-CHECKED, and keeps the Lean, replay and note cells of both parts.", "",
       "The verdicts and the code-gap rule are those of FORMAL-BRIEF.md and COVERAGE-FORMAL-AC.md. The",
       "findings and their resolutions are in COUNTEREXAMPLES.md and",
       "research/sherlock-e2e-spec-20261115/bus/formal-findings.md.", "",
       "## Totals", "", "| verdict | rows |", "|---|---|"]
for v in ("MODELED", "CONSTANT-CHECKED", "SPEC-CHECKED", "FINDING"):
    out.append(f"| {v} | {counts[v]} |")
out += [f"| total | {len(rows)} |", f"| rows that both parts hold (merged) | {len(shared)} |", ""]
fnd = [k for k, r in rows.items() if r["verdict"] == "FINDING"]
if fnd:
    out += ["FINDING rows: " + ", ".join(fnd) + " (verdicts and owner decisions in COUNTEREXAMPLES.md).", ""]
out += ["## Rows", "", "| ID | slice | context | verdict | Lean | replay | note |", "|---|---|---|---|---|---|---|"]
for k in sorted(rows):
    r = rows[k]
    out.append(f"| {k} | {r['slice']} | {r['ctx']} | {r['verdict']} | {r['lean']} | {r['replay']} | {r['note']} |")
(ROOT / "COVERAGE-FORMAL.md").write_text("\n".join(out) + "\n")
print(dict(counts), "total", len(rows), "shared", len(shared), "pointers", len(pointers))
