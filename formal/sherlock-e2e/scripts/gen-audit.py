#!/usr/bin/env python3
"""Generate <Ns>/Audit.lean for one context: `#audit_ns <Ns>` pinned at [] and
`#print axioms` pinned for every theorem of the context's modules (allowlist:
propext, Classical.choice, Quot.sound). Builds on odin twice (probe, then pinned).
Usage: gen-audit.py <context> <Namespace>"""
import pathlib, re, subprocess, sys
ctx, ns = sys.argv[1], sys.argv[2]
here = pathlib.Path(__file__).resolve().parent.parent
lean = here / ctx / "lean"
mods = sorted(p for p in (lean / ns).glob("*.lean") if p.name != "Audit.lean")
names = []
for p in mods:
    for m in re.finditer(r"^theorem\s+([A-Za-z0-9_']+)", p.read_text(), re.M):
        names.append(f"{ns}.{m.group(1)}")
HEAD = f'''import Lean
{chr(10).join("import " + ns + "." + p.stem for p in mods)}

/-!
# Audit (generated by `formal/sherlock-e2e/scripts/gen-audit.py`)

* `#audit_ns {ns}` lists `implemented_by`, `extern`, `csimp`, `unsafe`, `partial`,
  `partial_fixpoint`, `opaque` and `axiom` declarations; pinned at `[]`.
* `#print axioms` of every theorem, pinned: only `propext`, `Classical.choice` and
  `Quot.sound` may appear (no `sorryAx`, no `_native` axiom).
-/

open Lean Elab Command

elab "#audit_ns " n:ident : command => do
  let env ← getEnv
  let mut bad : Array String := #[]
  for (c, ci) in env.constants.toList do
    let inModule := match env.getModuleIdxFor? c with
      | some i => n.getId.isPrefixOf (env.header.moduleNames[i.toNat]!)
      | none => false
    if (n.getId.isPrefixOf c || inModule) && !(c matches .str _ "_unsafe_rec") then
      if (Compiler.getImplementedBy? env c).isSome then bad := bad.push s!"implemented_by {{c}}"
      if isExtern env c then bad := bad.push s!"extern {{c}}"
      if ci.isUnsafe then bad := bad.push s!"unsafe {{c}}"
      if (Lean.Elab.PartialFixpoint.eqnInfoExt.find? env c).isSome then
        bad := bad.push s!"partial_fixpoint {{c}}"
      if ci.isPartial then bad := bad.push s!"partial {{c}}"
      if (Compiler.CSimp.ext.getState env).map.contains c then bad := bad.push s!"csimp {{c}}"
      match ci with
      | .axiomInfo _ => bad := bad.push s!"axiom {{c}}"
      | .opaqueInfo _ => bad := bad.push s!"opaque {{c}}"
      | _ => pure ()
  logInfo m!"{{bad.qsort (· < ·)}}"

/-- info: [] -/
#guard_msgs in
#audit_ns {ns}
'''
audit = lean / ns / "Audit.lean"
audit.write_text(HEAD + "".join(f"\n#print axioms {n}\n" for n in names))
def build():
    subprocess.run([str(here / "scripts" / "odin-build.sh"), ctx], check=False, capture_output=True)
    return subprocess.run(["ssh", "odin", f"cat ~/sherlock/formal-e2e/{ctx}/build.log"],
                          capture_output=True, text=True).stdout
log = build()
msgs = {}
for m in re.finditer(r"'([^']+)' (depends on axioms: \[[^\]]*\]|does not depend on any axioms)", log.replace("\n  ", " ").replace("\n", " ")):
    msgs[m.group(1)] = re.sub(r"\s+", " ", m.group(0))
missing = [n for n in names if n not in msgs]
if missing:
    print(log[-4000:]); sys.exit(f"no axiom message for {missing}")
allowed = {"propext", "Classical.choice", "Quot.sound"}
for n, t in msgs.items():
    m = re.search(r"\[(.*)\]", t)
    ax = {a.strip() for a in m.group(1).split(",")} if m else set()
    if ax - allowed:
        sys.exit(f"{n}: axioms outside the allowlist: {ax - allowed}")
audit.write_text(HEAD + "".join(f"\n/-- info: {msgs[n]} -/\n#guard_msgs in\n#print axioms {n}\n" for n in names))
log = build()
rc = re.search(r"rc=(\d+)", subprocess.run(["ssh", "odin", f"cd ~/sherlock/formal-e2e/{ctx}/lean && ~/.elan/bin/lake build --wfail >/dev/null 2>&1; echo rc=$?"], capture_output=True, text=True).stdout)
print(f"{ctx}: {len(names)} theorems pinned; build rc={rc.group(1) if rc else '?'}")
